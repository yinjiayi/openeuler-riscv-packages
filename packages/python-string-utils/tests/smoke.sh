set -euo pipefail
export PYTHONDONTWRITEBYTECODE=1 PYTHONNOUSERSITE=1
unset PYTHONHOME PYTHONPATH
export PIP_NO_INDEX=1 PIP_CONFIG_FILE=/dev/null PIP_NO_CACHE_DIR=1
rpm -q -- python-string-utils python3-setuptools python3-wheel
python3 - <<'PY'
import ast
import hashlib
import importlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tarfile
import tempfile

shared = Path('/usr/share/python-string-utils')
archive = shared / 'upstream.tar.gz'
digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
assert digest(archive) == '60b76619a1015853ea9a3f9d106c159ac82aa110c54c635a7e2ba6d376fb797c'
def owned(p):
    q = subprocess.run(['rpm', '-qf', '--qf', '%{NAME}\n', str(p)], check=True, capture_output=True, text=True)
    assert q.stdout.splitlines() == ['python-string-utils'], (str(p), q.stdout)
owned(archive)
with tempfile.TemporaryDirectory(prefix='string-utils-original-') as temp:
    root = Path(temp)
    original = root / 'original'
    original.mkdir()
    blobs = {}
    with tarfile.open(archive) as stream:
        members = stream.getmembers()
        assert len({m.name.split('/')[0] for m in members}) == 1
        for m in members:
            assert not m.name.startswith('/') and '..' not in Path(m.name).parts
            assert not m.issym() and not m.islnk() and (m.isdir() or m.isfile())
            if m.isdir():
                continue
            rel = Path(*Path(m.name).parts[1:])
            assert str(rel) not in blobs and rel.parts
            raw = stream.extractfile(m).read()
            assert len(raw) == m.size
            dest = original / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(raw)
            blobs[str(rel)] = hashlib.sha256(raw).hexdigest()
    assert len(blobs) == 69
    runtime = {k: v for k, v in blobs.items() if k.startswith('string_utils/') and k.endswith('.py')}
    tests = {k: v for k, v in blobs.items() if k.startswith('tests/') and k.endswith('.py')}
    assert len(runtime) == 6 and len(tests) == 43
    assert sum(x.name.startswith('test_') for p in original.glob('tests/test_*.py') for x in ast.walk(ast.parse(p.read_bytes())) if isinstance(x, ast.FunctionDef)) == 407
    package = importlib.import_module('string_utils')
    site = Path(package.__file__).resolve().parent.parent
    for rel, expected in runtime.items():
        installed = site / rel
        assert digest(installed) == expected
        owned(installed)
    assert Path('/usr/share/doc/python-string-utils/README.md').read_bytes() == (original / 'README.md').read_bytes()
    owned(Path('/usr/share/doc/python-string-utils/README.md'))
    scratch = root / 'installed-default'
    scratch.mkdir()
    for rel, expected in tests.items():
        installed = shared / rel
        assert digest(installed) == expected
        owned(installed)
        dst = scratch / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(installed.read_bytes())
    assert not (scratch / 'string_utils').exists()
    # A child import guard checks every installed runtime module, not a filtered
    # subset of tests. No source runtime is placed on the child's import path.
    guard = root / 'guard'
    guard.mkdir()
    guard_code = '''import builtins, hashlib, sys
from pathlib import Path
EXPECTED = %r
SITE = Path(%r)
old = builtins.__import__
def checked(name, globals=None, locals=None, fromlist=(), level=0):
    value = old(name, globals, locals, fromlist, level)
    for key, mod in list(sys.modules.items()):
        if key == 'string_utils' or key.startswith('string_utils.'):
            path = Path(mod.__file__).resolve()
            relative = str(path.relative_to(SITE))
            assert relative in EXPECTED
            assert hashlib.sha256(path.read_bytes()).hexdigest() == EXPECTED[relative]
    return value
builtins.__import__ = checked
''' % (runtime, str(site))
    (guard / 'sitecustomize.py').write_text(guard_code)
    env = dict(os.environ, PYTHONPATH=str(guard), PYTHONDONTWRITEBYTECODE='1', PYTHONNOUSERSITE='1')
    subprocess.run([sys.executable, '-m', 'unittest'], cwd=scratch, env=env, check=True)
    assert all(digest(original / rel) == expected for rel, expected in blobs.items())
    # Replay the original build separately in its pristine full source tree;
    # its runtime is never used by the installed-default test subprocess.
    shim = root / 'python-bin'
    shim.mkdir()
    (shim / 'python').symlink_to(sys.executable)
    build_env = dict(os.environ, PATH=str(shim) + os.pathsep + os.environ['PATH'])
    build_env.pop('PYTHONPATH', None)
    subprocess.run(['bash', 'build.sh'], cwd=original, env=build_env, check=True)
    # MANIFEST is explicitly marked generated by distutils upstream. Building
    # may regenerate that inventory; no runtime/test/default source may change.
    assert all(digest(original / rel) == expected for rel, expected in blobs.items() if rel != 'MANIFEST')
    assert len(list((original / 'dist').glob('*.whl'))) == 1
    assert len(list((original / 'dist').glob('*.tar.gz'))) == 1
    print(json.dumps({'installed_default': 'whole python -m unittest passed', 'original_test_files': 42, 'static_methods': 407, 'runtime_files': 6, 'original_build_script': 'passed', 'historical_interpreter_matrix_claimed': False}))
PY
